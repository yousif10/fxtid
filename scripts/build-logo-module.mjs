// Converts the official FXT logo SVG (class-based styles) into an inline-fill
// markup string that can be embedded in card artwork, PDFs and PNG renders.
// The geometry is copied verbatim - the logo is never redrawn or distorted.
import fs from "node:fs";

const src = fs.readFileSync(new URL("../public/brand/logo.svg", import.meta.url), "utf8");
const classes = {};
for (const m of src.matchAll(/\.(st\d+)\s*\{\s*fill:\s*(#[0-9a-fA-F]+);?\s*\}/g)) classes[m[1]] = m[2];
const body = src.slice(src.indexOf("</defs>") + 7, src.lastIndexOf("</svg>"));
const inner = body
  .replace(/class="(st\d+)"/g, (_, c) => `fill="${classes[c]}"`)
  .replace(/\s*\n\s*/g, "")
  .trim();
const out = `// AUTO-GENERATED by scripts/build-logo-module.mjs from public/brand/logo.svg. Do not edit.
/** Tight bounding box of the artwork inside the original 1024x1024 artboard. */
export const LOGO_VIEWBOX = "108 81.5 777.5 835.4";
export const LOGO_ASPECT = 777.5 / 835.4;
export const LOGO_INNER = ${JSON.stringify(inner)};
`;
fs.writeFileSync(new URL("../src/lib/brand/logo.ts", import.meta.url), out);
console.log("logo module written", inner.length, "chars", classes);
