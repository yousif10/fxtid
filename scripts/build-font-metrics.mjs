// Generates advance-width tables for the Inter weights used on ID card artwork so
// text can be measured/fitted identically in the browser, PNG and PDF renderers.
import fs from "node:fs";
import * as fontkit from "fontkit";
import { fileURLToPath } from "node:url";

const weights = { 400: "400Regular", 500: "500Medium", 600: "600SemiBold", 700: "700Bold", 800: "800ExtraBold" };
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(c);
for (let c = 160; c <= 383; c++) chars.push(c); // Latin-1 + Latin Extended-A (UK/EU names)
for (const c of [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026]) chars.push(c);

const tables = {};
for (const [w, file] of Object.entries(weights)) {
  const font = fontkit.openSync(fileURLToPath(new URL(`../public/fonts/Inter_${file}.ttf`, import.meta.url)));
  const t = {};
  for (const c of chars) {
    const g = font.glyphForCodePoint(c);
    if (g && g.id !== 0) t[c] = Math.round((g.advanceWidth / font.unitsPerEm) * 10000) / 10000;
  }
  tables[w] = t;
}
const out = `// AUTO-GENERATED by scripts/build-font-metrics.mjs. Do not edit.
// Advance widths in em units for Inter, keyed by weight then code point.
export const INTER_ADVANCES: Record<number, Record<number, number>> = ${JSON.stringify(tables)};
`;
fs.writeFileSync(new URL("../src/lib/cards/font-metrics.ts", import.meta.url), out);
console.log("metrics written", Object.keys(tables[400]).length, "glyphs per weight");
